from flaskapp.travel_ai.agents.flight_agent.schemas import FlightInventoryItem, SeatInventory

_TRUE_STRINGS = {"true", "1", "yes"}


def _seat_inventory_from_row(row: dict) -> SeatInventory:
    return SeatInventory(
        window_available=int(row["seat_window_available"]),
        aisle_available=int(row["seat_aisle_available"]),
        max_adjacent_block=int(row["seat_max_adjacent_block"]),
        accessible_available=int(row["seat_accessible_available"]),
        standard_fee=float(row["seat_standard_fee"]),
        extra_legroom_available=int(row["seat_extra_legroom_available"]),
        extra_legroom_fee=float(row["seat_extra_legroom_fee"]),
        exit_row_available=int(row["seat_exit_row_available"]),
        exit_row_fee=float(row["seat_exit_row_fee"]),
    )


def _load_extended_csv() -> list[FlightInventoryItem]:
    csv_path = Path(__file__).parent / "seed_data_extended.csv"
    with csv_path.open(encoding="utf-8", newline="") as f:
        return [
            FlightInventoryItem(
                flight_id=row["flight_id"],
                carrier=row["carrier"],
                flight_no=row["flight_no"],
                origin_airport=row["origin_airport"],
                dest_airport=row["dest_airport"],
                dep_ts=row["dep_ts"],
                arr_ts=row["arr_ts"],
                duration_min=int(row["duration_min"]),
                price=float(row["price"]),
                cabin_class=row["cabin_class"],
                seats_available=int(row["seats_available"]),
                stops=int(row["stops"]),
                wheelchair_assist_available=row["wheelchair_assist_available"].strip().lower() in _TRUE_STRINGS,
                step_free_boarding=row["step_free_boarding"].strip().lower() in _TRUE_STRINGS,
                seat_inventory=_seat_inventory_from_row(row),
            )
            for row in csv.DictReader(f)
        ]


