"""Seed rows for Flight Agent: the golden-scenario flights plus a broader,
generated inventory across 5 routes for realistic-sized testing.

`GOLDEN_SCENARIO_FLIGHTS` mirrors localfolder/db_schema.md section 7 ("the
hardest scenario"): wheelchair user, budget SGD 4,000, SIN -> Tokyo (NRT),
depart 2026-09-01. SQ636 is the cheap red-eye arriving 23:40 that Hotel/
Transport later finds infeasible; SQ632 is the mid-priced option arriving
15:10 that the flow renegotiates to once budget is exceeded. Kept as
literal, unchanging Python objects — golden JSON scenarios (tests/golden/
flight_scenarios.json) and several unit tests hard-code their exact prices/
times, so nothing here should ever edit these 4 rows; add new flights
instead.

The other 100 rows come from `seed_data_extended.csv`, generated by
scripts/generate_flight_seed_csv.py (SIN <-> NRT/LHR/SYD/BKK/HKG, mixed
full-service/budget carriers, cabins, prices, and seat inventory) — a handful
of hand-picked flights isn't enough to exercise ranking/filtering meaningfully
or look like a real dataset; see that script's docstring for how it was
derived and why it's deterministic (same output every regeneration). The
extended rows carry `seat_inventory`; the 4 golden rows deliberately leave it
None (their scenarios predate seat modelling and don't need it, and their
2026-09-01/05 dates don't collide with any extended-row date, so seat rows
never interfere with the golden scenarios).

Plain Python data, not tied to any database — see flight/__init__.py.
Prices are illustrative SGD figures, not real fares (db_schema.md rule 3).
"""

from __future__ import annotations

import csv
