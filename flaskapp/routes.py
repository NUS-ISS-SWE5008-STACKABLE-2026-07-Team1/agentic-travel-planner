"""Session-authenticated browser pages."""

from __future__ import annotations

from functools import wraps
from urllib.parse import parse_qsl, urlsplit
from uuid import UUID

from flask import Blueprint, abort, current_app, flash, redirect, render_template, request, session, url_for
from werkzeug.exceptions import HTTPException
from werkzeug.security import generate_password_hash

from flaskapp.database import (
    authenticate_user, create_user, get_intake_conversation,
    get_user_for_password_reset, replace_password,
)
from flaskapp.countries import COUNTRIES
from flaskapp.places import city_options
from flaskapp.forms import LoginForm, RegistrationForm, ResetPasswordForm
from flaskapp.admin_auth import is_admin_email

pages_bp = Blueprint("pages", __name__)


def _safe_next(target: str) -> str | None:
    """Rebuild a `?next=` value as a URL of one of this app's routes, or None.

    The redirect is generated by url_for() from the route the path matches,
    never echoed from the request, so it cannot point anywhere this app does
    not serve: not another host, not a scheme-relative //evil.example, not a
    path no route answers. login_required only ever produces relative paths.
    """
    parts = urlsplit(target)
    if parts.scheme or parts.netloc or not parts.path.startswith("/"):
        return None
    try:
        endpoint, values = current_app.url_map.bind(request.host).match(parts.path, method="GET")
    except HTTPException:  # no such route, wrong method, or a redirect rule
        return None
    query = {k: v for k, v in parse_qsl(parts.query) if k not in values and not k.startswith("_")}
    return url_for(endpoint, **values, **query)


def login_required(view):
    """Redirect anonymous browser users to the sign-in page."""
    @wraps(view)
    def wrapped(*args, **kwargs):
        if not session.get("authenticated"):
            return redirect(url_for("pages.login", next=request.full_path.rstrip("?")))
        return view(*args, **kwargs)
    return wrapped


@pages_bp.route("/", methods=["GET", "POST"])
def login():
    if session.get("authenticated"):
        return redirect(url_for("pages.main"))

    form = LoginForm()
    if form.validate_on_submit():
        user = authenticate_user(form.email.data, form.password.data)
        if user:
            session.clear()
            session["authenticated"] = True
            session["user_id"] = user["id"]
            session["user_email"] = user["email"]
            session["user_name"] = user["name"] or "Traveller"
            session["user_country"] = user["country"] or ""
            session.permanent = bool(form.remember.data)
            destination = _safe_next(request.args.get("next", ""))
            return redirect(destination or url_for("pages.main"))
        flash("The email or password is incorrect.", "danger")

    return render_template("login.html", form=form)


@pages_bp.route("/register", methods=["GET", "POST"])
def register():
    if session.get("authenticated"):
        return redirect(url_for("pages.main"))

    form = RegistrationForm()
    if form.validate_on_submit():
        user = create_user(
            form.name.data,
            form.email.data,
            generate_password_hash(form.password.data),
            form.country.data,
            form.birthday.data.isoformat(),
        )
        if user is None:
            form.email.errors.append("An account with this email already exists.")
        else:
            session.clear()
            session["authenticated"] = True
            session["user_id"] = user["id"]
            session["user_email"] = user["email"]
            session["user_name"] = user["name"]
            session["user_country"] = user["country"] or ""
            flash("Your account has been created.", "success")
            return redirect(url_for("pages.main"))

    return render_template("register.html", form=form)


@pages_bp.route("/forgot-password", methods=["GET", "POST"])
def forgot_password():
    if session.get("authenticated"):
        return redirect(url_for("pages.main"))
    form = ResetPasswordForm()
    if form.validate_on_submit():
        user = get_user_for_password_reset(form.email.data)
        if user:
            replace_password(
                user["email"],
                user["password_hash"],
                generate_password_hash(form.password.data),
            )
            session.clear()
        flash(
            "If an account exists for that email, its password has been reset. You can now sign in.",
            "success",
        )
        return redirect(url_for("pages.login"))
    return render_template("forgot_password.html", form=form)


@pages_bp.get("/main")
@login_required
def main():
    # `city_options` is embedded in the page rather than fetched, so the
    # dependent city <select> repopulates instantly and the form still works if
    # a later request fails. It is public reference data — no per-user content.
    return render_template(
        "main.html", user_name=session.get("user_name", "Traveller"), countries=COUNTRIES,
        is_admin=is_admin_email(current_app.config, session.get("user_email")),
        user_country=session.get("user_country", ""),
        city_options=city_options(),
    )


@pages_bp.get("/chat/<uuid:request_id>")
@login_required
def chat(request_id: UUID):
    conversation = get_intake_conversation(
        current_app.config["DATABASE"], str(request_id), session.get("user_id")
    )
    return render_template(
        "chat.html", user_name=session.get("user_name", "Traveller"), request_id=request_id,
        intake_mode=False, conversation=conversation,
        is_admin=is_admin_email(current_app.config, session.get("user_email")),
    )


@pages_bp.get("/chat/intake")
@login_required
def intake_chat():
    """Host clarification before a complete request is sent to specialist agents."""
    return render_template(
        "chat.html", user_name=session.get("user_name", "Traveller"), countries=COUNTRIES,
        intake_mode=True,
        is_admin=is_admin_email(current_app.config, session.get("user_email")),
    )


@pages_bp.get("/admin")
@login_required
def admin():
    if not is_admin_email(current_app.config, session.get("user_email")):
        abort(403)
    return render_template("admin.html", user_name=session.get("user_name", "Administrator"))


@pages_bp.post("/logout")
@login_required
def logout():
    session.clear()
    flash("You have been signed out safely.", "success")
    return redirect(url_for("pages.login"))
